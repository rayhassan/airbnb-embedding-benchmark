st.markdown("---")
with st.expander("Architecture — key design decisions"):
    st.markdown(
        """
        ### One embedding field, three indexes

        | Field | Generated by | When |
        |---|---|---|
        | `emb_large` | `voyage-4-large`, `input_type="document"` | Setup (once) |

        | Index | Field | Atlas quantization | Similarity |
        |---|---|---|---|
        | `vs_none` | `emb_large` | none (float32) | cosine |
        | `vs_scalar` | `emb_large` | scalar (int8) | cosine |
        | `vs_binary` | `emb_large` | binary (1-bit) | euclidean |

        ### Why asymmetric retrieval works
        All `voyage-4` series models (`voyage-4-large`, `voyage-4`, `voyage-4-lite`)
        share the **same vector space**.  A query vector produced by `voyage-4-lite`
        is geometrically compatible with document vectors indexed by `voyage-4-large`.
        This means you can use a cheap query model against an expensive, high-quality
        index without reindexing — the **Model Comparison** page benchmarks whether
        the quality loss is acceptable.

        ### What quantization does
        Atlas-side quantization compresses the stored vectors at index time:
        - **scalar**: float32 → int8 (~4× smaller, very small accuracy loss)
        - **binary**: float32 → 1-bit (~32× smaller, larger accuracy loss, requires euclidean)

        The original `emb_large` float32 values in the document are unchanged —
        only the index representation changes.  The **Quantization** page lets you
        see exactly how much accuracy and latency change at each compression level.
        """
    )
